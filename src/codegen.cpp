#include "skillissue/ast.hpp"

#include <sstream>

namespace skillissue {
namespace {
std::string llvm_type(Type type) {
    if (type == Type::Int)
        return "i64";
    if (type == Type::Bool)
        return "i1";
    throw std::logic_error("unresolved type in code generation");
}

std::string escape_ir(std::string_view text) {
    const char hex[] = "0123456789ABCDEF";
    std::string result;
    for (const unsigned char c : text) {
        if (c >= 32 && c <= 126 && c != '"' && c != '\\')
            result += static_cast<char>(c);
        else {
            result += '\\';
            result += hex[c >> 4];
            result += hex[c & 15];
        }
    }
    return result;
}

struct Value {
    Type type;
    std::string name;
};

class Generator {
  public:
    Generator(const Program &program, const Source &source) : program_(program), source_(source) {}
    std::string run() {
        out_ << "; Generated by SkillIssue. Integer arithmetic wraps unless checked.\n"
             << "source_filename = \"" << escape_ir(source_.name) << "\"\n\n"
             << "@.source = private unnamed_addr constant [" << source_.name.size() + 1
             << " x i8] c\"" << escape_ir(source_.name) << "\\00\"\n\n"
             << "declare void @skill_yap_int(i64)\n"
             << "declare void @skill_yap_bool(i32)\n"
             << "declare i64 @skill_div(i64, i64, ptr, i32, i32)\n"
             << "declare i32 @skill_exit(i64, ptr, i32, i32)\n\n"
             << "define i32 @main() {\n";
        label("entry");
        for (std::size_t i = 0; i < program_.symbols.size(); ++i) {
            instruction(slot(i) + " = alloca " + llvm_type(program_.symbols[i].type));
        }
        statements(program_.body);
        if (!terminated_)
            throw std::logic_error("main has no terminator");
        out_ << "}\n";
        return out_.str();
    }

  private:
    const Program &program_;
    const Source &source_;
    std::ostringstream out_;
    std::size_t temporary_ = 0, next_block_ = 0;
    std::string block_;
    bool terminated_ = true;

    static std::string slot(std::size_t id) {
        return "%v" + std::to_string(id);
    }
    std::string temporary() {
        return "%t" + std::to_string(temporary_++);
    }
    std::string new_label(std::string_view prefix) {
        return std::string(prefix) + '.' + std::to_string(next_block_++);
    }
    void instruction(const std::string &text) {
        if (terminated_)
            throw std::logic_error("instruction after terminator");
        out_ << "  " << text << '\n';
    }
    void label(const std::string &name) {
        if (!terminated_)
            throw std::logic_error("unterminated basic block");
        out_ << name << ":\n";
        block_ = name;
        terminated_ = false;
    }
    void jump(const std::string &target) {
        instruction("br label %" + target);
        terminated_ = true;
    }
    void branch(const Value &condition, const std::string &yes, const std::string &no) {
        instruction("br i1 " + condition.name + ", label %" + yes + ", label %" + no);
        terminated_ = true;
    }
    static std::string location(Span span) {
        return "ptr @.source, i32 " + std::to_string(span.line) + ", i32 " +
               std::to_string(span.column);
    }
    Value logical(const Expr &expr) {
        const auto left = expression(*expr.left);
        const auto origin = block_;
        const auto rhs = new_label("logic.rhs"), end = new_label("logic.end");
        const bool is_and = expr.op == TokenKind::And;
        branch(left, is_and ? rhs : end, is_and ? end : rhs);
        label(rhs);
        const auto right = expression(*expr.right);
        // A nested logical expression can change the current predecessor block.
        const auto predecessor = block_;
        jump(end);
        label(end);
        const auto result = temporary();
        instruction(result + " = phi i1 [ " + (is_and ? "false" : "true") + ", %" + origin +
                    " ], [ " + right.name + ", %" + predecessor + " ]");
        return {Type::Bool, result};
    }
    Value expression(const Expr &expr) {
        switch (expr.kind) {
        case Expr::Kind::Integer:
            return {Type::Int, std::to_string(expr.integer)};
        case Expr::Kind::Boolean:
            return {Type::Bool, expr.boolean ? "true" : "false"};
        case Expr::Kind::Name: {
            const auto result = temporary();
            instruction(result + " = load " + llvm_type(expr.type) + ", ptr " + slot(expr.symbol));
            return {expr.type, result};
        }
        case Expr::Kind::Unary: {
            const auto value = expression(*expr.left);
            const auto result = temporary();
            instruction(result + (expr.op == TokenKind::Bang ? " = xor i1 " + value.name + ", true"
                                                             : " = sub i64 0, " + value.name));
            return {expr.type, result};
        }
        case Expr::Kind::Binary:
            if (expr.op == TokenKind::And || expr.op == TokenKind::Or)
                return logical(expr);
            break;
        }
        const auto left = expression(*expr.left);
        const auto right = expression(*expr.right);
        const auto result = temporary();
        std::string op;
        switch (expr.op) {
        case TokenKind::Plus:
            op = "add";
            break;
        case TokenKind::Minus:
            op = "sub";
            break;
        case TokenKind::Star:
            op = "mul";
            break;
        case TokenKind::Slash:
            instruction(result + " = call i64 @skill_div(i64 " + left.name + ", i64 " + right.name +
                        ", " + location(expr.span) + ")");
            return {Type::Int, result};
        case TokenKind::Equal:
            op = "icmp eq";
            break;
        case TokenKind::NotEqual:
            op = "icmp ne";
            break;
        case TokenKind::Less:
            op = "icmp slt";
            break;
        case TokenKind::LessEqual:
            op = "icmp sle";
            break;
        case TokenKind::Greater:
            op = "icmp sgt";
            break;
        case TokenKind::GreaterEqual:
            op = "icmp sge";
            break;
        default:
            throw std::logic_error("unsupported binary operator");
        }
        instruction(result + " = " + op + ' ' + llvm_type(left.type) + ' ' + left.name + ", " +
                    right.name);
        return {expr.type, result};
    }
    void statements(const std::vector<std::unique_ptr<Stmt>> &list) {
        for (const auto &statement : list) {
            const auto &stmt = *statement;
            switch (stmt.kind) {
            case Stmt::Kind::Declaration:
            case Stmt::Kind::Assignment: {
                const auto value = expression(*stmt.expression);
                instruction("store " + llvm_type(value.type) + ' ' + value.name + ", ptr " +
                            slot(stmt.symbol));
                break;
            }
            case Stmt::Kind::Print: {
                auto value = expression(*stmt.expression);
                if (value.type == Type::Bool) {
                    const auto wide = temporary();
                    instruction(wide + " = zext i1 " + value.name + " to i32");
                    instruction("call void @skill_yap_bool(i32 " + wide + ")");
                } else
                    instruction("call void @skill_yap_int(i64 " + value.name + ")");
                break;
            }
            case Stmt::Kind::Return: {
                const auto value = expression(*stmt.expression);
                const auto result = temporary();
                instruction(result + " = call i32 @skill_exit(i64 " + value.name + ", " +
                            location(stmt.span) + ")");
                instruction("ret i32 " + result);
                terminated_ = true;
                break;
            }
            case Stmt::Kind::Block:
                statements(stmt.body);
                break;
            case Stmt::Kind::If: {
                const auto condition = expression(*stmt.expression);
                const auto yes = new_label("then"), no = new_label("else"),
                           end = new_label("merge");
                branch(condition, yes, no);
                label(yes);
                statements(stmt.body);
                jump(end);
                label(no);
                statements(stmt.alternative);
                jump(end);
                label(end);
                break;
            }
            case Stmt::Kind::While: {
                const auto condition_block = new_label("cond"), body = new_label("body"),
                           end = new_label("exit");
                jump(condition_block);
                label(condition_block);
                const auto condition = expression(*stmt.expression);
                branch(condition, body, end);
                label(body);
                statements(stmt.body);
                jump(condition_block);
                label(end);
                break;
            }
            }
        }
    }
};
} // namespace

std::string generate_ir(const Program &program, const Source &source) {
    return Generator(program, source).run();
}

} // namespace skillissue
